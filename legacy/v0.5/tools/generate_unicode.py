"""Generate fixed Unicode 15.1 XID ranges from the vendored UCD."""
from pathlib import Path
p=Path(__file__).resolve().parents[1]
rows={k:[] for k in ['XID_Start','XID_Continue']}
for line in (p/'vendor/unicode/DerivedCoreProperties-15.1.0.txt').read_text().splitlines():
    data=line.split('#')[0].strip()
    if not data: continue
    nums,prop=map(str.strip,data.split(';')[:2])
    if prop not in rows: continue
    bounds=nums.split('..'); rows[prop].append((int(bounds[0],16),int(bounds[-1],16)))
out='// Generated by tools/generate_unicode.py; Unicode 15.1.0.\n'
for k,v in rows.items(): out+=f'pub const {k.upper()}: &[(u32,u32)] = &[\n'+''.join(f'({a},{b}),\n' for a,b in v)+'];\n'
(p/'src/syntax/unicode.rs').write_text(out)

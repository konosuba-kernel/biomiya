#!/usr/bin/env python3
"""Regenerate target arithmetic vectors with independent Python integer semantics."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]

def generate():
    chunks = ['// Generated by tools/generate_integer_audit.py. Expected values use unbounded Python integers.']
    calls = []
    vector = 0
    for bits, signed, name in [(b,s,('i' if s else 'u')+str(b)) for b in (8,16,32,64) for s in (False,True)] + [(64,False,'usize'),(64,True,'isize')]:
        low = -(1 << (bits-1)) if signed else 0
        high = (1 << (bits-1))-1 if signed else (1 << bits)-1
        mask = (1 << bits)-1
        def wrap(n):
            n &= mask
            return n-(1 << bits) if signed and n > high else n
        def literal(n):
            return f'{n}_{name}'
        pairs = [(0,1),(high,1),(low,high),(high,high),(low,-1 if signed else 2),(37,-7 if signed else 7)]
        for a,b in pairs:
            vector += 1
            function = f'vector_{vector}'
            lines = [f'fn {function}(a:{name}, b:{name})->i32 {{']
            checks = []
            for op,value in [('+%',a+b),('-%',a-b),('*%',a*b),('&',a&b),('|',a|b),('^',a^b)]:
                checks.append(f'(a {op} b) == {literal(wrap(value))}')
            for op,value in [('+',a+b),('-',a-b),('*',a*b)]:
                expected = f'Some(v) => v == {literal(value)}, None => false' if low<=value<=high else 'Some(_) => false, None => true'
                checks.append(f'match (a {op}? b) {{{expected}}}')
                if low<=value<=high:
                    checks.append(f'(a {op} b) == {literal(value)}')
            if b and not (signed and a == low and b == -1):
                quotient = (abs(a)//abs(b)) * (-1 if (a<0) != (b<0) else 1)
                checks += [f'(a / b) == {literal(quotient)}',f'(a % b) == {literal(a-quotient*b)}']
            for shift in (0,1,bits-1):
                checks += [f'(a << {literal(shift)}) == {literal(wrap(a<<shift))}',f'(a >> {literal(shift)}) == {literal(a>>shift)}']
            checks += [f'(a < b) == {str(a<b).lower()}',f'(a >= b) == {str(a>=b).lower()}',f'(~a) == {literal(wrap(~a))}']
            for n,expression in enumerate(checks,1):
                lines.append(f'    if !({expression}) {{ return {vector*100+n}; }}')
            lines.append('    0\n}')
            chunks.append('\n'.join(lines))
            calls.append(f'    let r_{vector}={function}({literal(a)},{literal(b)}); if r_{vector} != 0 {{ return r_{vector}; }}')
    chunks.append('fn test()->i32 {\n'+'\n'.join(calls)+'\n    0\n}')
    return '\n\n'.join(chunks)+'\n'

if __name__ == '__main__':
    (ROOT/'tests/audit/integer_vectors.vt').write_text(generate())
